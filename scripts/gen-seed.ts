// Writes supabase/seed.sql with the reference data (vendors, POs, approval rules).
// Bills, invoice PDFs, traces and the sample inbox need Storage uploads, so they are created by
// the reset-demo Edge Function (Settings → Mailbox → Reset demo data), which runs the real pipeline.
import { writeFileSync } from "node:fs";
import { SEED_POS, SEED_RULES, SEED_VENDORS } from "../supabase/functions/_shared/seed.ts";

const lit = (v: unknown): string =>
  v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : typeof v === "object" ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb` : `'${String(v).replace(/'/g, "''")}'`;
const insert = (table: string, rows: Record<string, unknown>[]) => {
  const cols = Object.keys(rows[0]);
  return `insert into ${table} (${cols.join(", ")}) values\n${rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n")}\non conflict (id) do nothing;\n`;
};
const sql = [
  "-- Generated by `npm run gen:seed`. Reference data only; run the reset-demo function for bills and the sample inbox.",
  insert("vendors", SEED_VENDORS as unknown as Record<string, unknown>[]),
  insert("purchase_orders", SEED_POS as unknown as Record<string, unknown>[]),
  insert("approval_rules", SEED_RULES as unknown as Record<string, unknown>[]),
].join("\n");
writeFileSync("supabase/seed.sql", sql);
console.log("wrote supabase/seed.sql");
